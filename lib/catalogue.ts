import destinationFactsData from './data/destination-facts.json'
import londonRoutesData from './data/routes/london.json'
import detailsData from './data/destination-details.json'
import type { Destination } from './types'

/** An IATA airport code. */
export type Airport = string

export interface Route {
  /** False when the trip needs a connection. */
  direct: boolean
  airports: Airport[]
  airlines: string[]
  /** True when every route to this destination from this origin is seasonal. */
  seasonalOnly: boolean
  /**
   * Hub IATA codes (`lib/data/hubs.json`) a connecting route passes through, in order. Absent
   * for a direct route. Added by ROADMAP.md feature 10; no generated route sets it yet, so every
   * route today is still `direct: true` with no `via`.
   */
  via?: Airport[]
}

type FactKey = 'id' | 'name' | 'country' | 'countryCode' | 'coordinates' | 'continent' | 'currency'

/** Facts every catalogue entry has, looked up from Wikipedia/Wikidata rather than written. */
export type DestinationFacts = Pick<Destination, FactKey>

/** Everything else about a destination, written in destination-details.json. */
export type DestinationDetails = Omit<Destination, FactKey>

/** A destination's routes, keyed by the departure city id that can reach it (`lib/departureCities.ts`). */
export type RoutesByOrigin = Partial<Record<string, Route>>

/**
 * A destination that may not have its details filled in yet. Only entries with every detail
 * (see `isPickable`) are ever recommended.
 */
export type CatalogueEntry = DestinationFacts &
  Partial<DestinationDetails> & {
    routes: RoutesByOrigin
  }

type GeneratedDestination = DestinationFacts & { routes: RoutesByOrigin }

type GeneratedRoute = Route & { id: string }

// Generated by `yarn data:routes <city-id>` — never edit by hand, overwritten on each run.
// Facts are shared across cities; routes are kept one file per origin city.
const destinationFacts = destinationFactsData as DestinationFacts[]
// Hand-maintained details for generated destinations, keyed by destination id.
const destinationDetails = detailsData as Record<string, Partial<DestinationDetails>>

/**
 * One generated route file per departure city with route data so far, keyed by that city's id
 * in `lib/departureCities.ts`. Add an entry here as each new city's `yarn data:routes <city-id>`
 * output lands (ROADMAP.md feature 8).
 */
const ROUTES_BY_ORIGIN_CITY: Record<string, GeneratedRoute[]> = {
  'london-uk': londonRoutesData as GeneratedRoute[],
}

/**
 * Joins shared destination facts with every origin city's routes, dropping any fact with no
 * route from any origin (e.g. a destination only another city's data has resolved so far).
 */
export function joinFactsAndRoutes(
  facts: DestinationFacts[],
  routesByOriginCity: Record<string, GeneratedRoute[]>
): GeneratedDestination[] {
  const routesById = new Map<string, RoutesByOrigin>()
  for (const [originId, cityRoutes] of Object.entries(routesByOriginCity)) {
    for (const { id, direct, airports, airlines, seasonalOnly, via } of cityRoutes) {
      const existing = routesById.get(id) ?? {}
      existing[originId] = { direct, airports, airlines, seasonalOnly, ...(via ? { via } : {}) }
      routesById.set(id, existing)
    }
  }

  return facts.flatMap((fact) => {
    const routes = routesById.get(fact.id)
    return routes ? [{ ...fact, routes }] : []
  })
}

const generatedDestinations: GeneratedDestination[] = joinFactsAndRoutes(
  destinationFacts,
  ROUTES_BY_ORIGIN_CITY
)

/**
 * Builds the catalogue from the generated destinations, which are the source of truth for where
 * each supported city can fly to, merging in whatever details have been written for each.
 */
export function buildCatalogue(
  generated: GeneratedDestination[],
  details: Record<string, Partial<DestinationDetails>>
): CatalogueEntry[] {
  return generated.map((destination) => ({ ...destination, ...details[destination.id] }))
}

/** True when an entry has every detail the recommendation engine and destination UI rely on. */
export function isPickable(entry: CatalogueEntry): entry is CatalogueEntry & Destination {
  return (
    entry.estimatedCosts !== undefined &&
    entry.travelStyles !== undefined &&
    entry.travelStyles.length > 0 &&
    entry.bestMonths !== undefined &&
    entry.description !== undefined &&
    entry.climate !== undefined &&
    entry.activities !== undefined
  )
}

export const catalogue = buildCatalogue(generatedDestinations, destinationDetails)

/** The destinations the engine may recommend, from at least one supported origin city. */
export const pickableDestinations: Destination[] = catalogue.filter(isPickable)

/**
 * The destinations the engine may recommend from this origin city specifically — pickable, and
 * reachable from it. "Reachable" is a direct route today; feature 10 adds one-stop connections.
 * Also keeps a city from recommending itself once it has its own catalogue entry, since a
 * destination's own route data never lists itself as an origin.
 */
export function getPickableDestinations(originId: string): Destination[] {
  return catalogue.filter(
    (entry): entry is CatalogueEntry & Destination =>
      isPickable(entry) && entry.routes[originId] !== undefined
  )
}
